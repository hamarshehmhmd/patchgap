import pytest

from patchgap.versions import deb_cmp, rpm_cmp


@pytest.mark.parametrize("a,b,r", [
    ("1.0", "1.0", 0), ("1.0", "1.1", -1), ("1.10", "1.9", 1),
    ("1.0~rc1", "1.0", -1), ("1.0", "1.0+b1", -1), ("1:1.0", "2.0", 1),
    ("6.8.0-149.149", "6.8.0-117.117", 1), ("6.8.0-149.149~22.04.1", "6.8.0-149.149", -1),
    ("6.12.113-1~deb12u1", "6.12.113-1", -1), ("1:9.2p1-2+deb12u3", "1:9.2p1-2+deb12u2", 1),
    ("1:9.6p1-3ubuntu13.3", "1:9.6p1-3ubuntu13.11", -1), ("1.0-1", "1.0-1", 0),
    ("2.0a", "2.0", 1), ("1.0-", "1.0", 0),
])
def test_deb(a, b, r):
    assert deb_cmp(a, b) == r
    assert deb_cmp(b, a) == -r


@pytest.mark.parametrize("a,b,r", [
    ("5.14.0-687.64.1.el9_8", "5.14.0-687.64.1.el9_8", 0),
    ("5.14.0-687.64.1.el9_8", "5.14.0-687.63.1.el9_8", 1),
    ("5.14.0-700.1.1.el9_8", "5.14.0-687.64.1.el9_8", 1),
    ("4.18.0-553.182.1.el8_10", "4.18.0-553.99.1.el8_10", 1),
    ("1.0~rc1", "1.0", -1), ("1.0^post", "1.0", 1), ("1.0a", "1.0", 1),
    ("1:1.0-1", "2.0-1", 1), ("6.1.189-236.400.amzn2023", "6.1.188-1.amzn2023", 1),
    ("1.010", "1.9", 1), ("1.0", "1.0.0", -1),
])
def test_rpm(a, b, r):
    assert rpm_cmp(a, b) == r
    assert rpm_cmp(b, a) == -r
